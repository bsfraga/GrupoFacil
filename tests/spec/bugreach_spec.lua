-- Bug report no Forever: nomes com sobrenome e jogador que não alcança o admin (outra regra,
-- outra facção ou horários que nunca batem) -> link dos comentários no CurseForge.
local T = require("t")
local H = require("helpers")
local describe, it = T.describe, T.it

local URL = "https://www.curseforge.com/wow/addons/grupofacil/comments"
local function world(admins)
    return H.world({ beforeAddonLoaded = function(_, ns) ns.BUG_ADMINS = admins or { "Bael Goldmaker" } end })
end
local function report(w, p, text)
    p:slash("/gf bug")
    local f = p.env.GrupoFacilBugFrame
    p:type(f.note.box, text or "algo quebrou")
    p:click(f.send)
    return f, H.ns(p).MyBugReports()[1]
end

describe("bug report: nomes com sobrenome (Forever)", function()
    it("admin configurado com nome completo recebe, grava e responde; o jogador vê o desfecho", function()
        local w = world()
        local a = H.login(w, { name = "Bael", surname = "Goldmaker", account = "AUTOR" })
        local p = H.login(w, { name = "Jogador", surname = "Silva", account = "JOGADOR" })
        w:advance(10)
        T.ok(H.ns(a).bugAdmin, "UnitName só com o primeiro nome deve reconhecer o admin")
        T.no(H.ns(p).bugAdmin)
        local _, e = report(w, p)
        w:advance(40)
        local inbox = H.ns(a).BugInbox()
        T.eq(#inbox, 1, "não chegou ao admin")
        T.eq(inbox[1].from, "Jogador Silva", "o remetente vem com sobrenome e é para ele que a resposta vai")
        a:reload(); w:advance(70)
        T.eq(e.state, "done")
        H.ns(a).ResolveBug(e.id, "fixed", "ok")
        w:advance(3)
        T.eq(e.resolved and e.resolved.status, "fixed")
        T.eq(H.ns(p).BugReach(), "ok")
        T.clean(p); T.clean(a)
    end)

    it("com o sobrenome vindo de UnitName, o admin de verdade continua admin", function()
        local w = world()
        local a = H.login(w, { name = "Bael", surname = "Goldmaker", account = "AUTOR", unitNameSurname = true })
        w:advance(10)
        T.ok(H.ns(a).bugAdmin)
        T.clean(a)
    end)

    it("outro jogador com o mesmo primeiro nome não se passa pelo admin", function()
        local w = world()
        local p = H.login(w, { name = "Jogador", surname = "Silva", account = "JOGADOR" })
        -- se o jogo der o sobrenome no 2º valor de UnitName, o impostor nem se acha admin
        local fake = H.login(w, { name = "Bael", surname = "Impostor", account = "OUTRO", unitNameSurname = true })
        w:advance(10)
        T.no(H.ns(fake).bugAdmin, "Bael Impostor virou admin")
        local _, e = report(w, p)
        H.ns(p).BugChannel._onAddon("GFBUG", "1~A2~" .. e.id, "WHISPER", "Bael Impostor")
        T.no(e.state == "done", "aceitou confirmação de um impostor")
        T.clean(p)
    end)
end)

describe("bug report: admin fora do alcance", function()
    it("outra regra (PvP): o report espera, e depois de muitas tentativas o jogo sugere o CurseForge", function()
        local w = world()
        local a = H.login(w, { name = "Bael", surname = "Goldmaker", account = "AUTOR", ruleset = "normal" })
        local p = H.login(w, { name = "Jogador", surname = "Silva", account = "JOGADOR", ruleset = "pvp" })
        w:advance(10)
        local f, e = report(w, p)
        T.eq(H.ns(p).BugReach(), "trying")
        T.match(p:text(f.linkText), "another ruleset", "o link aparece sempre")
        T.eq(p:text(f.link), URL)
        T.no(H.shown(p, f.linkWarn))
        w:advance(4 * 3600)
        T.eq(e.state, "queued", "não pode ter chegado")
        T.eq(#H.ns(a).BugInbox(), 0)
        T.eq(H.ns(p).BugReach(), "unlikely")
        T.match(p:text(f.linkText), "has not reached the author yet")
        T.ok(H.shown(p, f.linkWarn), "aviso em destaque")
        local warns = 0
        for _, l in ipairs(p:chatLines()) do if l:find("leave a comment on CurseForge: " .. URL, 1, true) then warns = warns + 1 end end
        T.eq(warns, 1, "avisa no chat uma vez por sessão")
        T.ok(p.hiddenSystem and p.hiddenSystem > 0, "as linhas 'No player named' continuam escondidas")
        T.clean(p); T.clean(a)
    end)

    it("vale também para facção diferente; o aviso volta no login seguinte e /gf bug link dá o endereço", function()
        local w = world()
        H.login(w, { name = "Bael", surname = "Goldmaker", account = "AUTOR", faction = "Alliance" })
        local p = H.login(w, { name = "Jogador", surname = "Silva", account = "JOGADOR", faction = "Horde" })
        w:advance(10)
        report(w, p)
        w:advance(4 * 3600)
        T.eq(H.ns(p).BugReach(), "unlikely")
        p:reload(); w:advance(30)
        T.has(p:chatLines(), "leave a comment on CurseForge", "não avisou de novo depois do /reload")
        p:slash("/gf bug link")
        T.has(p:chatLines(), "comments on CurseForge: " .. URL:gsub("%p", "%%%0"))
        T.clean(p)
    end)

    it("dias sem resposta contam; quando o admin aparece tudo volta ao normal", function()
        local w = world()
        local p = H.login(w, { name = "Jogador", surname = "Silva", account = "JOGADOR" })
        w:advance(10)
        local f, e = report(w, p)
        w:advance(200)
        local r = H.db(p).bugReach
        T.ok(r and (r.misses or 0) >= 1, "o PING sem resposta deveria contar")
        r.days["2026-01-01"] = true -- um dia anterior sem resposta
        T.eq(H.ns(p).BugReach(), "unlikely")
        local a = H.login(w, { name = "Bael", surname = "Goldmaker", account = "AUTOR" })
        w:advance(1000)
        T.eq(H.ns(p).BugReach(), "ok", "o admin respondeu")
        T.ok(e.state == "received" or e.state == "done", "o report saiu: " .. tostring(e.state))
        T.no(H.shown(p, f.linkWarn), "o aviso some")
        T.clean(p); T.clean(a)
    end)

    it("o link é só para copiar: digitar não muda, clicar seleciona tudo", function()
        local w = world()
        local p = H.login(w, { name = "Jogador", surname = "Silva", account = "JOGADOR" })
        w:advance(10)
        p:slash("/gf bug")
        local box = p.env.GrupoFacilBugFrame.link
        p:type(box, "lixo")
        T.eq(p:text(box), URL)
        T.ok(p.ui.state(box).highlight, "selecionou para copiar")
        T.eq(#p:hover(box) > 0, true)
        T.clean(p)
    end)

    it("as Novidades também trazem o link direto", function()
        local w = world()
        local p = H.login(w, { name = "Jogador", surname = "Silva", account = "JOGADOR" })
        w:advance(5)
        local n = p.env.GrupoFacilWhatsNew
        T.ok(n and H.shown(p, n))
        T.eq(p:text(n.link), URL)
        T.clean(p)
    end)

    it("sem admin configurado não há tentativa e o estado é 'none'", function()
        local w = world({ "<ADMIN_1>" })
        local p = H.login(w, { name = "Jogador", account = "JOGADOR" })
        w:advance(10)
        report(w, p)
        w:advance(3600)
        T.eq(H.ns(p).BugReach(), "none")
        T.clean(p)
    end)
end)
