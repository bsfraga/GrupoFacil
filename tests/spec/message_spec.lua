-- Texto do pedido de vaga: padrão em inglês, variáveis, limpeza de pontuação, spec e classe.
local T = require("t")
local H = require("helpers")
local describe, it = T.describe, T.it

local TALENTS = { { name = "Beast Mastery", spent = 5 }, { name = "Marksmanship", spent = 21 }, { name = "Survival", spent = 0 } }

describe("mensagem de pedido de vaga", function()
    it("padrão em inglês com level, spec (árvore com mais pontos) e classe", function()
        local w = H.world()
        local c = H.login(w, { level = 27, talents = TALENTS })
        T.eq(H.ns(c).BuildMessage(), "Hi, I'm a level 27 Marksmanship Hunter, can I join your group?")
        T.clean(c)
    end)

    it("sem pontos de talento a spec some e não sobra espaço duplo", function()
        local w = H.world()
        local c = H.login(w, { level = 9 })
        T.eq(H.ns(c).BuildMessage(), "Hi, I'm a level 9 Hunter, can I join your group?")
    end)

    it("todas as variáveis, em inglês e nos apelidos em português", function()
        local w = H.world()
        local c = H.login(w, { name = "Ana", level = 20, class = "PRIEST", talents = { { name = "Holy", spent = 10 } } })
        c.data.roles = { tank = false, healer = true, dps = true }
        local ns = H.ns(c)
        ns.SetTemplate("{name}/{nome} {class}/{classe} {spec} {level} {role}/{funcao} {activity}/{dungeon}/{masmorra} {xyz}")
        T.eq(ns.BuildMessage({ activityName = "Deadmines" }),
            "Ana/Ana Priest/Priest Holy 20 Healer/DPS/Healer/DPS Deadmines/Deadmines/Deadmines {xyz}")
        T.eq(ns.BuildMessage():match("%[dungeon%]"), "[dungeon]", "prévia sem grupo mostra [dungeon]")
    end)

    it("limpa espaço antes de pontuação e espaços repetidos", function()
        local w = H.world()
        local c = H.login(w, { level = 30 })
        local ns = H.ns(c)
        ns.SetTemplate("  Oi  {spec}  ,  sou {class} !  ")
        T.eq(ns.BuildMessage(), "Oi, sou Hunter!")
    end)

    it("texto vazio ou igual ao padrão volta ao padrão (não grava)", function()
        local w = H.world()
        local c = H.login(w)
        local ns = H.ns(c)
        ns.SetTemplate("x {level}")
        T.eq(H.db(c).template, "x {level}")
        ns.SetTemplate("   ")
        T.eq(H.db(c).template, nil)
        ns.SetTemplate(ns.DEFAULT_TEMPLATE)
        T.eq(H.db(c).template, nil)
        local t, custom = ns.GetTemplate()
        T.eq(t, ns.DEFAULT_TEMPLATE); T.eq(custom, false)
    end)

    it("spec e classe escolhidas valem só para o personagem; auto volta à detecção", function()
        local w = H.world()
        local c = H.login(w, { level = 30, talents = TALENTS })
        c:slash("/gf spec Sniper")
        c:slash("/gf class Caçador")
        T.eq(H.ns(c).BuildMessage(), "Hi, I'm a level 30 Sniper Caçador, can I join your group?")
        T.eq(H.char(c).spec, "Sniper")
        local alt = H.login(w, { name = "Alt", account = c.account, level = 30, talents = TALENTS })
        T.match(H.ns(alt).BuildMessage(), "Marksmanship Hunter", "outro personagem não herda")
        c:slash("/gf spec auto")
        c:slash("/gf class auto")
        T.match(H.ns(c).BuildMessage(), "Marksmanship Hunter")
        T.clean(c)
    end)

    it("talentos mudaram (TRAIT_CONFIG_UPDATED) e level subiu: a spec é recalculada", function()
        local w = H.world()
        local c = H.login(w, { level = 30, talents = TALENTS })
        local ns = H.ns(c)
        T.match(ns.BuildMessage(), "Marksmanship")
        c.data.talents = { { name = "Beast Mastery", spent = 30 }, { name = "Marksmanship", spent = 1 } }
        T.match(ns.BuildMessage(), "Marksmanship", "em cache até o evento")
        c:fireEvent("TRAIT_CONFIG_UPDATED", 1)
        T.match(ns.BuildMessage(), "Beast Mastery")
        c.level = 31
        c:fireEvent("PLAYER_LEVEL_UP", 31)
        T.match(ns.BuildMessage(), "level 31")
        T.clean(c)
    end)

    it("roles secretas: {role} fica vazio, sem erro", function()
        local w = H.world()
        local c = H.login(w)
        c.data.rolesSecret = true
        local ns = H.ns(c)
        ns.SetTemplate("eu sou {role} .")
        T.eq(ns.BuildMessage(), "eu sou.")
        T.clean(c)
    end)

    it("texto persiste depois do /reload e /gf msg mostra como sai", function()
        local w = H.world()
        local c = H.login(w, { level = 12 })
        c:slash("/gf msg Bora {level}?")
        T.has(c:chatLines(), "new text: Bora 12%?")
        c:reload()
        c:clearChat()
        c:slash("/gf msg")
        T.has(c:chatLines(), "text %(custom%): Bora {level}%?")
        T.has(c:chatLines(), "goes out as: Bora 12%?")
        c:slash("/gf msg default")
        T.eq(H.db(c).template, nil)
        T.has(c:chatLines(), "default text %(English%)")
        T.clean(c)
    end)

    it("a mensagem padrão mais longa cabe num sussurro (255 bytes)", function()
        local w = H.world()
        local c = H.login(w, { level = 60, talents = { { name = string.rep("X", 40), spent = 50 } } })
        c:slash("/gf class " .. string.rep("Y", 40))
        T.ok(#H.ns(c).BuildMessage() <= 255)
    end)
end)
