-- Janela de Novidades: abre a cada carga até marcar "Já li" (por versão), destaque do bug report.
local T = require("t")
local H = require("helpers")
local describe, it = T.describe, T.it

local function setup()
    local w = H.world({ beforeAddonLoaded = function(_, ns) ns.BUG_ADMINS = { "Bael" } end })
    local c = H.login(w, { account = "A" })
    return w, c
end
local function news(c) return c.env.GrupoFacilWhatsNew end

describe("novidades", function()
    it("abre sozinha alguns segundos depois de entrar, com a versão e o destaque do report", function()
        local w, c = setup()
        w:advance(1)
        T.no(news(c) and H.shown(c, news(c)), "não abre antes da tela de carregamento sumir")
        w:advance(3)
        local f = news(c)
        T.ok(f and H.shown(c, f), "não abriu no login")
        T.match(c:text(f.TitleText) or "", "GrupoFacil " .. H.ns(c).NEWS_VERSION:gsub("%.", "%%."))
        T.ok(H.find(c, f, "^New: report a problem to the author$", true), "destaque do report")
        T.no(f.ack:GetChecked(), "começa desmarcado")
        T.ok(H.shown(c, f.hint), "avisa que volta enquanto não marcar")
        c:click(f.report)
        T.ok(H.shown(c, c.env.GrupoFacilBugFrame), "o botão do destaque abre a janela de report")
        T.clean(c)
    end)

    it("sem marcar 'Já li' volta a cada /reload e a cada login, mesmo fechada", function()
        local w, c = setup()
        w:advance(4)
        c:click(news(c).close)
        T.no(H.shown(c, news(c)))
        c:reload(); w:advance(4)
        T.ok(H.shown(c, news(c)), "voltou depois do /reload")
        c:logout(); w:advance(5)
        c = H.login(w, { account = "A" }); w:advance(4)
        T.ok(H.shown(c, news(c)), "voltou no login seguinte")
        T.clean(c)
    end)

    it("marcar 'Já li' grava a versão e para de abrir; /gf news ainda abre; desmarcar volta a abrir", function()
        local w, c = setup()
        w:advance(4)
        c:click(news(c).ack)
        T.eq(H.db(c).newsSeen, H.ns(c).NEWS_VERSION)
        T.no(H.shown(c, news(c).hint))
        c:reload(); w:advance(10)
        T.no(news(c) and H.shown(c, news(c)), "abriu de novo depois de marcar")
        c:slash("/gf news")
        T.ok(H.shown(c, news(c)), "/gf news abre")
        T.ok(news(c).ack:GetChecked(), "mostra marcado")
        c:click(news(c).ack)
        T.eq(H.db(c).newsSeen, nil)
        c:reload(); w:advance(4)
        T.ok(H.shown(c, news(c)), "desmarcado volta a abrir")
        T.clean(c)
    end)

    it("quem marcou numa versão anterior vê as notas novas", function()
        local w, c = setup()
        w:advance(4)
        c:click(news(c).ack)
        H.db(c).newsSeen = "0.12.0"
        c:reload(); w:advance(4)
        T.ok(H.shown(c, news(c)))
        T.clean(c)
    end)

    it("carga em combate: espera sair do combate para abrir", function()
        local w, c = setup()
        w:advance(4)
        c:reload()
        c:enterCombat()
        w:advance(6)
        T.no(news(c) and H.shown(c, news(c)), "abriu no meio do combate")
        c:leaveCombat()
        T.ok(H.shown(c, news(c)), "não abriu ao sair do combate")
        T.clean(c)
    end)

    it("abre pelas opções e pelos apelidos do comando", function()
        local w, c = setup()
        w:advance(4)
        c:click(news(c).ack); news(c):Hide()
        c:slash("/gf options")
        local b = H.find(c, c.env.GrupoFacilOptionsFrame, "^What's New$")
        T.ok(b, "botão nas opções")
        c:click(b)
        T.ok(H.shown(c, news(c)))
        news(c):Hide()
        c:slash("/gf novidades")
        T.ok(H.shown(c, news(c)))
        c:slash("/gf help")
        T.has(c:chatLines(), "/gf news")
        T.clean(c)
    end)
end)

describe("destaque do report na janela principal", function()
    it("o ícone brilha até a primeira vez que a janela de report abre, e isso fica gravado", function()
        local w, c = setup()
        w:advance(4)
        c:slash("/gf")
        local bug = c.env.GrupoFacilFrame.bugButton
        w:advance(0.5)
        T.ok(H.shown(c, bug.glow), "sem brilho no começo")
        c:click(bug)
        w:advance(0.5)
        T.no(H.shown(c, bug.glow), "brilho continua depois de abrir o report")
        T.eq(H.db(c).bugWindowOpened, true)
        c:reload(); w:advance(4)
        c:slash("/gf")
        w:advance(0.5)
        T.no(H.shown(c, c.env.GrupoFacilFrame.bugButton.glow), "brilho voltou depois do /reload")
        T.clean(c)
    end)
end)
