-- Opções (janela própria e Options > AddOns), botão do minimapa, menu de addons e tour.
local T = require("t")
local H = require("helpers")
local describe, it = T.describe, T.it

-- abre a janela de opções (na seção pedida, se houver)
local function opts(c, section)
    c:slash("/gf options" .. (section and (" " .. section) or ""))
    return c.env.GrupoFacilOptionsFrame
end
local function section(c, key) H.ns(c).OptionsSection(key) end
local function find(c, root, pat) return H.find(c, root, pat, true) end
-- a caixa de seleção cujo rótulo (c.label, ao lado) casa com pat
local function checkOf(c, root, pat)
    local function walk(f)
        for _, ch in ipairs({ f:GetChildren() }) do
            if c.ui.state(ch).kind == "CheckButton" and ch.label and (c:text(ch.label) or ""):find(pat) and c.ui.visible(ch) then return ch end
            local h = walk(ch)
            if h then return h end
        end
    end
    return walk(root)
end

describe("opções, minimapa e tour", function()
    it("registra em Options > AddOns e abre a janela própria ao lado da principal", function()
        local w = H.world()
        local c = H.login(w)
        T.eq(c.settingsCategories[1].name, "GrupoFacil")
        c:slash("/gf")
        local f = opts(c)
        T.ok(H.shown(c, f))
        T.eq(select(2, f:GetPoint(1)), c.env.GrupoFacilFrame)
        T.ok(find(c, f, "^version dev  ·  /gf opens the window$"))
        c:slash("/gf options")
        T.no(H.shown(c, f), "segundo /gf options fecha")
        T.clean(c)
    end)

    it("seções: Geral, Mensagens, Missões, Convide um amigo e Ajuda; cada uma mostra só o seu contexto", function()
        local w = H.world()
        local c = H.login(w)
        local f = opts(c)
        local w2 = f.content
        T.eq(w2.section, "general", "abre em Geral")
        for _, name in ipairs({ "^General$", "^Messages$", "^Quests$", "^Invite a friend$", "^Help$" }) do
            T.ok(find(c, f, name), name)
        end
        T.ok(c.ui.visible(w2.auto)); T.no(c.ui.visible(w2.msg)); T.no(c.ui.visible(w2.autoInvite))
        c:click(find(c, f, "^Messages$"))
        T.ok(c.ui.visible(w2.msg)); T.no(c.ui.visible(w2.auto))
        c:click(find(c, f, "^Quests$"))
        T.ok(c.ui.visible(w2.autoInvite)); T.no(c.ui.visible(w2.msg))
        c:click(find(c, f, "^Help$"))
        T.ok(find(c, f, "^Report a problem$")); T.ok(find(c, f, "^What's New$"))
        -- o rodapé (autoria e apoio) aparece em todas
        T.ok(c.ui.visible(w2.donate))
        c:click(find(c, f, "^General$"))
        T.ok(c.ui.visible(w2.donate))
        -- a página do jogo (Options > AddOns) tem as mesmas seções
        T.ok(H.find(c, c.env.GrupoFacilOptionsPanel, "^Invite a friend$"))
        T.clean(c)
    end)

    it("Apoiar no GitHub mostra o link do GitHub Sponsors para copiar", function()
        local w = H.world()
        local c = H.login(w)
        local f = opts(c)
        local b = find(c, f, "^Sponsor on GitHub$")
        T.ok(b, "botão no rodapé das opções")
        T.has(c:hover(b), "github.com/sponsors/bsfraga")
        c:click(b)
        local d = c.env.GrupoFacilDonateFrame
        T.ok(H.shown(c, d))
        T.eq(d.box:GetText(), "https://github.com/sponsors/bsfraga")
        c:type(d.box, "outra coisa")
        T.eq(d.box:GetText(), "https://github.com/sponsors/bsfraga", "só leitura")
        T.clean(c)
    end)

    it("a engrenagem é o último botão do cabeçalho; não há mais botão Opções embaixo", function()
        local w = H.world()
        local c = H.login(w)
        c:slash("/gf")
        local f = c.env.GrupoFacilFrame
        local gear = f.optionsButton
        T.ok(H.shown(c, gear))
        local gr, qr = c.ui.rect(gear), c.ui.rect(f.tabQuests)
        T.ok(gr.l >= qr.r, "depois da aba Missões")
        T.ok(gr.t > c.ui.rect(f).t - 30, "no cabeçalho")
        -- nenhum outro botão do cabeçalho à direita da engrenagem (o X do quadro não conta)
        for _, b in ipairs({ f.bugButton, f.tabDungeons, f.tabQuests }) do
            T.ok(c.ui.rect(b).r <= gr.l, "botão do cabeçalho depois da engrenagem")
        end
        T.eq(find(c, f.dungeonPanel, "^Options$"), nil, "o botão Opções de baixo saiu")
        c:click(gear)
        T.ok(H.shown(c, c.env.GrupoFacilOptionsFrame))
        T.clean(c)
    end)

    it("mensagem: digitar e Enter grava, prévia acompanha; Padrão volta ao inglês", function()
        local w = H.world()
        local c = H.login(w, { level = 33 })
        local f = opts(c, "messages")
        local box
        local function walk(x)
            for _, ch in ipairs({ x:GetChildren() }) do
                if c.ui.state(ch).kind == "EditBox" and c.ui.visible(ch) and not box then box = ch end
                walk(ch)
            end
        end
        walk(f)
        c:type(box, "Bora {level}!")
        c:press(box, "ENTER")
        T.eq(H.db(c).template, "Bora {level}!")
        T.ok(find(c, f, "^Goes out as: Bora 33!$"))
        c:click(find(c, f, "^Default$"))
        T.eq(H.db(c).template, nil)
        T.ok(find(c, f, "^Goes out as: Hi, I'm a level 33 Hunter"))
        T.clean(c)
    end)

    it("spec e classe pelas opções valem só para este personagem; vazio volta ao automático", function()
        local w = H.world()
        local c = H.login(w, { talents = { { name = "Survival", spent = 9 } } })
        local f = opts(c, "messages")
        T.ok(find(c, f, "now: Survival"))
        local boxes = {}
        local function walk(x) for _, ch in ipairs({ x:GetChildren() }) do if c.ui.state(ch).kind == "EditBox" then boxes[#boxes + 1] = ch end walk(ch) end end
        walk(f)
        c:type(boxes[2], "  Arqueiro  ")
        c.ui.clearFocus()
        T.eq(H.char(c).spec, "Arqueiro")
        c:type(boxes[3], "Caçador")
        c:press(boxes[3], "ENTER")
        T.eq(H.char(c).classe, "Caçador")
        T.match(H.ns(c).BuildMessage(), "Arqueiro Caçador")
        c:type(boxes[2], "")
        c:press(boxes[2], "ENTER")
        T.eq(H.char(c).spec, nil)
        T.clean(c)
    end)

    it("caixas de seleção mudam o modo de envio, abrir junto, encaixe, minimapa, hook e debug", function()
        local w = H.world()
        local c = H.login(w)
        local f = opts(c, "messages")
        c:click(checkOf(c, f, "^Only open the chat with the text"))
        T.eq(H.db(c).sendMode, "preencher")
        c:click(checkOf(c, f, "^Send the whisper straight"))
        T.eq(H.db(c).sendMode, "direto")
        section(c, "general")
        c:click(checkOf(c, f, "^Open together with Looking For Group$"))
        T.eq(H.db(c).autoOpen, false)
        c:click(checkOf(c, f, "^Show minimap button$"))
        T.no(H.shown(c, c.env.GrupoFacilMinimapButton))
        c:click(checkOf(c, f, "^Capture the native search"))
        T.eq(H.db(c).hookSearch, false)
        section(c, "help")
        c:click(checkOf(c, f, "^Show the diagnostic trace in chat$"))
        T.eq(H.db(c).debug, true)
        c:clearChat()
        H.ns(c).D.Trace("X", "linha de teste")
        T.has(c:chatLines(), "X linha de teste")
        T.clean(c)
    end)

    it("Desbloquear todos só fica ativo com alguém bloqueado", function()
        local w = H.world()
        local c = H.login(w)
        local f = opts(c)
        local b = find(c, f, "^Unblock all$")
        T.no(b:IsEnabled())
        H.db(c).blocked.fulano = "Fulano"
        f:Hide(); f:Show()
        T.ok(find(c, f, "^Blocked players: 1$"))
        T.ok(b:IsEnabled())
        c:click(b)
        T.eq(next(H.db(c).blocked), nil)
        T.clean(c)
    end)

    it("seletor de idioma lista as 6 línguas e pede /reload", function()
        local w = H.world()
        local c = H.login(w)
        local f = opts(c)
        c:click(find(c, f, "^English  v$"))
        local m = c.env.GrupoFacilLanguageMenu
        T.ok(H.shown(c, m))
        for _, n in ipairs({ "English", "Português %(Brasil%)", "Español %(España%)", "Español %(Latinoamérica%)", "Deutsch", "Français" }) do
            T.ok(find(c, m, "^" .. n .. "$"), n)
        end
        c:click(find(c, m, "^Deutsch$"))
        T.eq(H.db(c).language, "de")
        T.ok(H.shown(c, c.env.GrupoFacilReloadPrompt))
        T.clean(c)
    end)

    it("Abrir o menu do jogo em combate é recusado com aviso", function()
        local w = H.world()
        local c = H.login(w)
        c:enterCombat()
        H.ns(c).OpenGameOptions()
        T.has(c:chatLines(), "open the options after combat")
        c:leaveCombat()
        H.ns(c).OpenGameOptions()
        T.eq(c.openedCategory, "GrupoFacil")
        T.clean(c)
    end)

    it("minimapa: clique abre a janela, direito as opções, arrastar grava o ângulo; /gf minimap off esconde", function()
        local w = H.world()
        local c = H.login(w)
        local b = c.env.GrupoFacilMinimapButton
        T.ok(H.shown(c, b))
        T.has(c:hover(b), "Drag: move the button")
        c:click(b, "LeftButton")
        T.ok(H.shown(c, c.env.GrupoFacilFrame))
        c:click(b, "RightButton")
        T.ok(H.shown(c, c.env.GrupoFacilOptionsFrame))
        local mx, my = c.env.Minimap:GetCenter()
        c.cursor = { mx + 100, my } -- à direita: 0 graus
        c.ui.fire(b, "OnDragStart")
        w:advance(0.1)
        c.ui.fire(b, "OnDragStop")
        T.near(H.db(c).minimap.angle, 0, 0.5)
        c:slash("/gf minimap off")
        T.no(H.shown(c, b))
        c:reload()
        T.no(H.shown(c, c.env.GrupoFacilMinimapButton), "continua escondido depois do /reload")
        T.clean(c)
    end)

    it("menu de addons do jogo: clique abre a janela, direito as opções, tooltip", function()
        local w = H.world()
        local c = H.login(w)
        c.env.GrupoFacil_OnAddonCompartmentClick(nil, "LeftButton")
        T.ok(H.shown(c, c.env.GrupoFacilFrame))
        c.env.GrupoFacil_OnAddonCompartmentClick(nil, "RightButton")
        T.ok(H.shown(c, c.env.GrupoFacilOptionsFrame))
        T.clean(c)
    end)

    it("tour: aviso na primeira abertura, passos com Próximo/Voltar, concluir marca como visto", function()
        local w = H.world()
        local c = H.login(w)
        c:slash("/gf")
        local ns = H.ns(c)
        local banner, callout = ns.TourFrames()
        T.ok(H.shown(c, banner), "banner de primeiro uso")
        c:click(find(c, banner, "^Start tour$"))
        T.ok(H.shown(c, callout))
        T.ok(find(c, callout, "^1/%d+  Pick what to list$"))
        c:click(callout.next)
        T.ok(find(c, callout, "^2/"))
        c:click(callout.back)
        T.ok(find(c, callout, "^1/"))
        for _ = 1, 10 do if H.shown(c, callout) then c:click(callout.next) end end
        T.no(ns.TourRunning())
        T.has(c:chatLines(), "Tour finished")
        c.env.GrupoFacilFrame:Hide(); c:slash("/gf")
        T.no(H.shown(c, banner), "não aparece de novo")
        T.clean(c)
    end)

    it("tour no modo compacto mostra os filtros e depois volta; combate interrompe", function()
        local w = H.world()
        local c = H.login(w)
        H.db(c).compact = true
        c:slash("/gf")
        H.ns(c).ApplyCompact()
        c:slash("/gf tour")
        T.ok(find(c, c.env.GrupoFacilFrame, "^Near me$"), "filtros aparecem no tour")
        c:enterCombat()
        T.no(H.ns(c).TourRunning())
        T.no(find(c, c.env.GrupoFacilFrame, "^Near me$"), "volta ao compacto")
        c:slash("/gf tour")
        T.has(c:chatLines(), "not available in combat")
        c:leaveCombat()
        T.clean(c)
    end)

    it("Pular o tour marca como visto e avisa como ver de novo", function()
        local w = H.world()
        local c = H.login(w)
        c:slash("/gf tour")
        local _, callout = H.ns(c).TourFrames()
        c:click(callout.skip)
        T.has(c:chatLines(), "/gf tour")
        T.no(H.ns(c).TourRunning())
    end)
end)
