-- Leitura dos resultados do Looking For Group: campos, secret values, lockdown, atualizações e busca.
local T = require("t")
local H = require("helpers")
local describe, it = T.describe, T.it

local function entryOf(ns, name)
    for _, id in ipairs(ns.order) do
        local e = ns.entries[id]
        if e and e.name == name then return e end
    end
end

describe("resultados do Looking For Group", function()
    it("lê jogador solo e grupo com composição, vagas, atividade e zona", function()
        local w = H.world()
        H.sampleListings(w)
        local c = H.login(w)
        H.search(w, c)
        local ns = H.ns(c)
        T.eq(#ns.order, 6)
        local p = entryOf(ns, "Padre")
        T.eq(p.solo, true); T.eq(p.level, 22); T.eq(p.class, "PRIEST")
        T.eq(p.roles.healer, true); T.eq(p.roles.tank, false)
        T.eq(p.activity, "Wailing Caverns"); T.eq(p.zone, "Elwynn Forest")
        T.eq(p.specName, nil, "specName igual à classe não vira spec")
        local g = entryOf(ns, "Lider")
        T.eq(g.solo, false); T.eq(g.numMembers, 3); T.eq(g.maxPlayers, 5)
        T.deepEq(g.counts, { tank = 1, healer = 0, dps = 2 })
        T.deepEq(g.remaining, { tank = 0, healer = 1, dps = 1 })
        T.eq(#g.members, 3); T.eq(g.members[1].leader, true)
        T.eq(g.zone, "Westfall")
        T.match(ns.status, "6 results in total")
        T.clean(c)
    end)

    it("várias atividades: nome da primeira + contagem", function()
        local w = H.world()
        w.lfg:add({ leader = "Multi", activityIDs = { 2, 1, 4 } })
        local c = H.login(w)
        H.search(w, c)
        T.eq(entryOf(H.ns(c), "Multi").activity, "Wailing Caverns +2")
    end)

    it("campos secretos: a listagem é descartada, as outras seguem, sem erro", function()
        local w = H.world()
        w.lfg:add({ leader = "Ok" })
        w.lfg:add({ leader = "Seg1", secret = { leaderName = true } })
        w.lfg:add({ leader = "Seg2", secretInfo = true })
        w.lfg:add({ leader = "Seg3", secretID = true })
        w.lfg:add({ leader = "Lvl", secret = { level = true } })
        local c = H.login(w)
        H.search(w, c)
        local ns = H.ns(c)
        T.ok(entryOf(ns, "Ok"))
        T.no(entryOf(ns, "Seg1")); T.no(entryOf(ns, "Seg2"))
        local l = entryOf(ns, "Lvl")
        T.ok(l, "level secreto não descarta a linha"); T.eq(l.level, nil)
        T.eq(#ns.order, 4, "id secreto não entra na ordem")
        T.clean(c)
    end)

    it("nome do líder ainda não chegou: linha sem nome, sem erro; atualização preenche", function()
        local w = H.world()
        local id = w.lfg:add({ leader = "Lento", pendingName = true })
        local c = H.login(w)
        H.search(w, c)
        local ns = H.ns(c)
        T.eq(ns.entries[id].name, nil)
        w.lfg:update(id, { pendingName = false })
        w:advance(0.2)
        T.eq(ns.entries[id].name, "Lento")
        T.clean(c)
    end)

    it("um membro com erro não derruba o grupo", function()
        local w = H.world()
        w.lfg:add({ leader = "Chefe", memberError = 2, members = {
            { name = "Chefe", level = 20, class = "MAGE", role = "TANK" }, { name = "X", level = 20, class = "MAGE" },
            { name = "Y", level = 21, class = "ROGUE" } } })
        local c = H.login(w)
        H.search(w, c)
        local e = entryOf(H.ns(c), "Chefe")
        T.ok(e); T.eq(#e.members, 2)
        T.clean(c)
    end)

    it("própria listagem (hasSelf) não aparece", function()
        local w = H.world()
        w.lfg:add({ leader = "Jogador", hasSelf = true })
        local c = H.login(w)
        H.search(w, c)
        T.eq(next(H.ns(c).entries), nil)
    end)

    it("restrição de chat: a lista congela e volta na próxima busca", function()
        local w = H.world()
        H.sampleListings(w)
        local c = H.login(w)
        H.search(w, c)
        local ns = H.ns(c)
        c.chatLockdown = true
        H.search(w, c)
        T.eq(ns.stale, true)
        T.match(ns.status, "list frozen")
        T.eq(#ns.order, 6, "lista anterior fica")
        c.chatLockdown = false
        w:advance(4)
        H.search(w, c)
        T.eq(ns.stale, false)
        T.clean(c)
    end)

    it("busca sem resposta sai de 'Searching...' em 10 s", function()
        local w = H.world()
        local c = H.login(w)
        w.lfg.noAnswer = true
        c:nativeSearch(2)
        local ns = H.ns(c)
        T.eq(ns.searching, true)
        w:advance(9)
        T.eq(ns.searching, true)
        w:advance(1.5)
        T.eq(ns.searching, false)
        T.match(ns.status, "got no answer")
        T.clean(c)
    end)

    it("busca recusada (throttled): mantém a lista e segura o botão por 6 s", function()
        local w = H.world()
        H.sampleListings(w)
        local c = H.login(w)
        H.search(w, c)
        c:nativeSearch(2, { 1, 2, 3, 4, 5 }); c:nativeSearch(2, { 1, 2, 3, 4, 5 })
        w:advance(1)
        local ns = H.ns(c)
        T.match(ns.status, "Too many searches")
        T.eq(#ns.order, 6)
        local ok, why = ns.SearchAgain()
        T.eq(ok, false); T.match(why, "wait %d+ s")
        w:advance(6)
        T.eq((ns.SearchAgain()), true)
        T.clean(c)
    end)

    it("Buscar de novo repete categoria e atividades da última busca nativa", function()
        local w = H.world()
        H.sampleListings(w)
        local c = H.login(w)
        c:nativeSearch(2, { 1, 3 })
        w:advance(4)
        local ns = H.ns(c)
        T.eq((ns.SearchAgain()), true)
        T.deepEq(c.lastSearch.activities, { 1, 3 })
        T.eq(c.lastSearch.category, 2)
        local ok, why = ns.SearchAgain()
        T.eq(ok, false, "intervalo de 3 s entre buscas"); T.match(why, "wait")
        T.clean(c)
    end)

    it("sem busca anterior, Buscar de novo busca todas as masmorras", function()
        local w = H.world()
        local c = H.login(w)
        local ok = H.ns(c).SearchAgain()
        T.eq(ok, true)
        T.eq(c.lastSearch.category, 2)
        T.eq(#c.lastSearch.activities, 5)
        T.clean(c)
    end)

    it("amigos, guilda e ignorados são marcados; mudanças nas listas refazem sem nova busca", function()
        local w = H.world()
        H.sampleListings(w)
        local c = H.login(w, { guild = "Guilda" })
        c.data.friends = { "Padre" }
        c.data.guildMembers = { "Tanque" }
        H.search(w, c)
        local ns = H.ns(c)
        T.eq(entryOf(ns, "Padre").relation, "friend")
        T.eq(entryOf(ns, "Tanque").relation, "guild")
        c.data.ignored = { "Arqueiro" }
        c:fireEvent("IGNORELIST_UPDATE")
        w:advance(0.6)
        T.eq(entryOf(ns, "Arqueiro").ignored, true)
        T.clean(c)
    end)

    it("amigo do Battle.net jogando WoW conta como amigo", function()
        local w = H.world()
        H.sampleListings(w)
        local c = H.login(w)
        c.data.bnet = { { { clientProgram = "WoW", wowProjectID = 2, characterName = "Arqueiro" } } }
        H.search(w, c)
        T.eq(entryOf(H.ns(c), "Arqueiro").relation, "friend")
    end)
end)
