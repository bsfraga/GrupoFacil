-- Comandos /gf: cada um, os apelidos em português e a ajuda.
local T = require("t")
local H = require("helpers")
local describe, it = T.describe, T.it

describe("comandos /gf", function()
    it("/gf e /grupofacil abrem e fecham a janela", function()
        local w = H.world()
        local c = H.login(w)
        c:slash("/gf")
        T.ok(H.shown(c, c.env.GrupoFacilFrame))
        c:slash("/grupofacil")
        T.no(H.shown(c, c.env.GrupoFacilFrame))
        T.clean(c)
    end)

    it("comando desconhecido mostra a ajuda inteira, sem a linha do admin", function()
        local w = H.world()
        local c = H.login(w)
        c:slash("/gf help")
        local lines = c:chatLines()
        for _, pat in ipairs({ "^/gf %- open or close", "^/gf options", "^/gf tour", "^/gf lang", "^/gf msg %- show", "^/gf spec", "^/gf class",
            "^/gf mode", "^/gf auto", "^/gf dock", "^/gf minimap", "^/gf hook", "^/gf blocked", "^/gf diag", "^/gf bug %- report", "^/gf debug" }) do
            T.has(lines, pat)
        end
        T.hasnt(lines, "^/gf bugs %-", "linha do admin escondida de quem não é admin")
        T.clean(c)
    end)

    it("apelidos em português funcionam", function()
        local w = H.world()
        local c = H.login(w)
        c:slash("/gf opcoes")
        T.ok(H.shown(c, c.env.GrupoFacilOptionsFrame))
        c:slash("/gf modo preencher")
        T.eq(H.db(c).sendMode, "preencher")
        c:slash("/gf modo direto")
        T.eq(H.db(c).sendMode, "direto")
        c:slash("/gf bloqueados")
        T.has(c:chatLines(), "no blocked players")
        c:slash("/gf erros")
        T.has(c:chatLines(), "GrupoFacil diag")
        c:slash("/gf reportar")
        T.ok(H.shown(c, c.env.GrupoFacilBugFrame))
        c:slash("/gf idioma pt")
        T.eq(H.db(c).language, "pt")
        T.clean(c)
    end)

    it("/gf auto, /gf hook e /gf debug mostram o estado", function()
        local w = H.world()
        local c = H.login(w)
        c:slash("/gf auto off"); T.eq(H.db(c).autoOpen, false)
        c:slash("/gf auto on"); T.eq(H.db(c).autoOpen, true)
        T.has(c:chatLines(), "open together with Looking For Group: on")
        c:slash("/gf hook"); T.has(c:chatLines(), "search hook: on")
        c:slash("/gf hook off"); T.eq(H.db(c).hookSearch, false)
        c:slash("/gf debug on"); T.eq(H.db(c).debug, true)
        T.has(c:chatLines(), "debug: on %(trace in chat%)")
        c:slash("/gf debug off"); T.eq(H.db(c).debug, false)
        T.clean(c)
    end)

    it("/gf blocked lista em ordem; /gf unblock sem nome explica", function()
        local w = H.world()
        local c = H.login(w)
        H.db(c).blocked = { zeca = "Zeca", ana = "Ana" }
        c:slash("/gf blocked")
        T.has(c:chatLines(), "blocked players: Ana, Zeca")
        c:slash("/gf unblock")
        T.has(c:chatLines(), "/gf unblock <name> | all")
        c:slash("/gf unblock todos")
        T.has(c:chatLines(), "blocked list cleared")
        T.clean(c)
    end)

    it("/gf spec sem talentos diz que não há pontos", function()
        local w = H.world()
        local c = H.login(w)
        c:slash("/gf spec")
        T.has(c:chatLines(), "spec: %(no talent points%)")
        c:slash("/gf class")
        T.has(c:chatLines(), "class: Hunter")
    end)

    it("comandos com espaços e maiúsculas", function()
        local w = H.world()
        local c = H.login(w)
        c:slash("/gf   MODE   PREFILL  ")
        T.eq(H.db(c).sendMode, "preencher")
        c:slash("/gf Auto OFF")
        T.eq(H.db(c).autoOpen, false)
        T.clean(c)
    end)

    it("nenhum comando dá erro, mesmo sem argumentos ou com lixo", function()
        local w = H.world()
        local c = H.login(w)
        for _, cmd in ipairs({ "", "options", "tour", "lang", "lang zz", "msg", "msg default", "spec", "spec auto", "class", "class auto",
            "mode", "mode x", "auto", "minimap", "minimap x", "dock", "hook", "hook x", "blocked", "unblock", "unblock x", "diag", "diag snap",
            "diag clear", "bug list", "bugs", "bugs list", "debug", "|cffff0000x|r", "%s%d", string.rep("a", 300) }) do
            c:slash("/gf " .. cmd)
        end
        T.clean(c)
    end)
end)
