-- Interface do bug report: janela do jogador, caixa de entrada do admin, comandos e opções.
local T = require("t")
local H = require("helpers")
local describe, it = T.describe, T.it

local function bugWorld(config)
    config = config or {}
    config.beforeAddonLoaded = function(_, ns) ns.BUG_ADMINS = { "Bael" } end
    return H.world(config)
end
local function setup(config)
    local w = bugWorld(config)
    local a = H.login(w, { name = "Bael", account = "AUTOR" })
    local p = H.login(w, { name = "Jogador", account = "JOGADOR" })
    w:advance(10)
    return w, a, p
end
local function count(t) local n = 0; for _ in pairs(t) do n = n + 1 end; return n end

describe("bug report: janela do jogador", function()
    it("abre por /gf bug, pelo botão da janela principal e pelas opções", function()
        local w, a, p = setup()
        p:slash("/gf bug")
        local f = p.env.GrupoFacilBugFrame
        T.ok(H.shown(p, f), "/gf bug não abriu")
        T.ok(p.ui.focus == f.note.box, "o texto deveria receber o foco")
        f:Hide()
        p:slash("/gf")
        p:click(p.env.GrupoFacilFrame.bugButton)
        T.ok(H.shown(p, f), "botão da barra de título não abriu")
        T.has(p:hover(p.env.GrupoFacilFrame.bugButton), "Report a problem")
        f:Hide()
        p:slash("/gf options help")
        local found = H.find(p, p.env.GrupoFacilOptionsFrame, "^Report a problem$")
        T.ok(found, "botão nas opções")
        p:click(found)
        T.ok(H.shown(p, f))
        T.clean(p)
    end)

    it("Enviar fica desligado sem texto; enviar cria o report, limpa o campo e mostra o id", function()
        local w, a, p = setup()
        p:slash("/gf bug")
        local f = p.env.GrupoFacilBugFrame
        T.no(f.send:IsEnabled(), "sem texto não envia")
        p:type(f.note.box, "   ")
        T.no(f.send:IsEnabled(), "só espaço não conta")
        p:type(f.note.box, "A lista não atualiza depois de uma busca")
        T.ok(f.send:IsEnabled())
        T.eq(p:text(f.counter), "40/1000")
        p:click(f.send)
        local list = H.ns(p).MyBugReports()
        T.eq(#list, 1)
        T.eq(p:text(f.note.box), "")
        T.match(p:text(f.status), "Report " .. list[1].id:gsub("%-", "%%-") .. " created")
        T.match(list[1].body, "\nkind=bug\n")
        T.ok(H.shown(p, f.save), "deve oferecer gravar em disco (/reload)")
        T.clean(p)
    end)

    it("tipo do report e diagnóstico opcional vão no corpo", function()
        local w, a, p = setup()
        p:slash("/gf bug")
        local f = p.env.GrupoFacilBugFrame
        p:click(f.kinds[2]) -- texto/tradução
        T.ok(f.kinds[2]:GetChecked())
        T.no(f.kinds[1]:GetChecked(), "funciona como rádio")
        p:click(f.diag) -- desliga o diagnóstico
        T.no(f.diag:GetChecked())
        p:type(f.note.box, "Tradução errada no botão")
        p:click(f.send)
        local e = H.ns(p).MyBugReports()[1]
        T.match(e.body, "\nkind=text\n")
        T.nomatch(e.body, "%-%-%-log", "sem diagnóstico não vai o rastro")
        T.nomatch(e.body, "settings=")
        T.clean(p)
    end)

    it("o aviso de criado fica na linha do Enviar; trechos não partem letras acentuadas", function()
        local w, a, p = setup()
        p:slash("/gf bug")
        local f = p.env.GrupoFacilBugFrame
        p:type(f.note.box, ("ação "):rep(30))
        p:click(f.send)
        local rs, rb = p.ui.rect(f.status), p.ui.rect(f.send)
        T.ok(rs and math.abs((rs.t + rs.b) / 2 - (rb.t + rb.b) / 2) < 2, "status fora da linha do botão")
        T.ok(rs.r <= p.ui.rect(f).r - 10, "status sai pela direita")
        local ns = H.ns(p)
        T.eq(ns.Utf8Sub("ação", 2), "aç")
        T.eq(ns.Utf8Sub("ação", 10), "ação")
        local snip = ns.MyBugReports()[1].snip
        T.eq(ns.Utf8Len(snip), 60)
        T.ok(snip:match("^ação ação"), snip)
        T.nomatch(p:text(f.rows[1]), "[\192-\255]|r", "corte no meio de uma letra")
        T.clean(p)
    end)

    it("o limite de 1000 caracteres conta letras acentuadas como uma", function()
        local w, a, p = setup()
        p:slash("/gf bug")
        local f = p.env.GrupoFacilBugFrame
        p:type(f.note.box, ("ã"):rep(1200))
        T.eq(p:text(f.counter), "1000/1000")
        T.eq(#p:text(f.note.box), 2000, "1000 caracteres de 2 bytes")
    end)

    it("a lista 'Seus reports' acompanha o estado sozinha (fila, recebido, entregue, corrigido)", function()
        local w, a, p = setup()
        p:slash("/gf bug")
        local f = p.env.GrupoFacilBugFrame
        T.ok(H.shown(p, f.empty))
        p:type(f.note.box, "um problema")
        p:click(f.send)
        T.match(p:text(f.rows[1]), "waiting for the author")
        T.no(H.shown(p, f.empty))
        w:advance(30)
        T.match(p:text(f.rows[1]), "received; waiting for the author to save it")
        a:reload()
        w:advance(70)
        T.match(p:text(f.rows[1]), "delivered")
        T.eq(H.ns(p).MyBugReports()[1].body, nil, "entregue: o corpo sai do disco")
        T.match(p:text(f.rows[1]), "um problema", "mas o trecho do texto continua na lista")
        local id = H.ns(p).MyBugReports()[1].id
        H.ns(a).ResolveBug(id, "fixed", "ok na 0.13")
        w:advance(3)
        T.match(p:text(f.rows[1]), "fixed: ok na 0.13")
        T.clean(p)
        T.clean(a)
    end)

    it("'Gravar agora' abre o prompt seguro de /reload; o clique recarrega e o aviso some", function()
        local w, a, p = setup()
        p:slash("/gf bug")
        local f = p.env.GrupoFacilBugFrame
        p:type(f.note.box, "x")
        p:click(f.send)
        p:click(f.save)
        local prompt = p.env.GrupoFacilReloadPrompt
        T.ok(H.shown(p, prompt))
        T.match(p:text(prompt.msg), "writes your report to disk")
        local reloads = p.reloads or 0
        p:click(p.env.GrupoFacilReloadButton)
        w:advance(0.1)
        T.eq(p.reloads, reloads + 1, "o botão seguro deveria recarregar")
        p:slash("/gf bug")
        T.no(H.shown(p, p.env.GrupoFacilBugFrame.save), "depois do reload não precisa mais")
        T.clean(p)
    end)

    it("abre e fecha em combate (não tem frame protegido)", function()
        local w, a, p = setup()
        p:enterCombat()
        p:slash("/gf bug")
        local f = p.env.GrupoFacilBugFrame
        T.ok(H.shown(p, f))
        f:Hide()
        T.no(H.shown(p, f))
        T.eq(#p.blocked, 0, "nenhuma ação bloqueada")
        T.clean(p)
    end)

    it("jogador comum não vê a caixa de entrada nem /gf bugs", function()
        local w, a, p = setup()
        p:slash("/gf bug")
        T.no(H.shown(p, p.env.GrupoFacilBugFrame.inbox))
        p:slash("/gf bugs")
        T.eq(p.env.GrupoFacilBugInbox, nil)
        T.has(p:chatLines(), "only the addon's author receives bug reports")
    end)

    it("/gf bug <texto> cria direto e avisa na primeira vez; /gf bug list mostra a fila", function()
        local w, a, p = setup()
        p:slash("/gf bug o tooltip some rápido demais")
        T.has(p:chatLines(), "goes to the author of GrupoFacil")
        T.has(p:chatLines(), "queued")
        p:clearChat()
        p:slash("/gf bug segundo")
        T.hasnt(p:chatLines(), "goes to the author of GrupoFacil", "aviso só na primeira vez")
        p:clearChat()
        p:slash("/gf bug list")
        T.has(p:chatLines(), "your bug reports %(2%)")
        T.clean(p)
    end)
end)

describe("bug report: caixa de entrada do admin", function()
    local function withReports(n)
        local w, a, p = setup()
        for i = 1, n do H.ns(p).SubmitBug("problema número " .. i, "bug", true); w:advance(1) end
        w:advance(30 * n)
        return w, a, p
    end

    it("lista os novos, abre o detalhe com o corpo inteiro e escapa |", function()
        local w, a, p = withReports(1)
        local id = H.ns(p).MyBugReports()[1].id
        H.db(a).inbox[id].body = H.db(a).inbox[id].body .. "texto com |cffff0000cor|r"
        a:slash("/gf bugs")
        local f = a.env.GrupoFacilBugInbox
        T.ok(H.shown(a, f))
        T.eq(a:text(f.newBtn), "New (1)")
        T.match(a:text(f.rows[1].label), "Jogador")
        T.match(a:text(f.rows[1].label), "problema número 1")
        a:click(f.rows[1])
        T.match(a:text(f.head), id:gsub("%-", "%%-"))
        T.match(a:text(f.head), "not on disk yet")
        T.match(a.ui.state(f.body.box).text, "||cffff0000cor||r", "| precisa vir escapado")
        -- só leitura
        a:type(f.body.box, "apagado")
        T.match(a:text(f.body.box), "problema número 1")
        T.clean(a)
    end)

    it("Corrigido com nota: muda o status, avisa o jogador; Triado não avisa", function()
        local w, a, p = withReports(2)
        a:slash("/gf bugs")
        local f = a.env.GrupoFacilBugInbox
        a:click(f.rows[1])
        local id1 = f.selected
        a:type(f.noteBox, "resolvido")
        a:click(f.actions[1])
        T.eq(H.db(a).inbox[id1].status, "fixed")
        T.eq(H.db(a).inbox[id1].note, "resolvido")
        T.eq(a:text(f.newBtn), "New (1)")
        a:click(f.rows[1])
        local id2 = f.selected
        a:click(f.actions[4])
        T.eq(H.db(a).inbox[id2].status, "triaged")
        w:advance(5)
        local mine = H.db(p).bugs
        T.eq(mine[id1].resolved and mine[id1].resolved.status, "fixed")
        T.eq(mine[id2].resolved, nil, "triado é só para o admin")
        T.clean(a)
        T.clean(p)
    end)

    it("filtro Novos/Todos, paginação e rolagem", function()
        local w, a, p = withReports(15)
        a:slash("/gf bugs")
        local f = a.env.GrupoFacilBugInbox
        T.eq(a:text(f.page), "1-12 of 15")
        a:click(f.down)
        T.eq(a:text(f.page), "4-15 of 15", "a última página fica cheia, como na lista principal")
        a:click(f.up)
        a:click(f.rows[1]); a:click(f.actions[1])
        T.eq(a:text(f.newBtn), "New (14)")
        T.eq(a:text(f.page), "1-12 of 14")
        a:click(f.allBtn)
        T.eq(a:text(f.page), "1-12 of 15")
        a.ui.fire(f, "OnMouseWheel", -1)
        T.eq(a:text(f.page), "4-15 of 15")
        T.clean(a)
    end)

    it("Exportar mostra todos os novos, do mais velho ao mais novo, para copiar", function()
        local w, a, p = withReports(3)
        a:slash("/gf bugs export")
        local f = a.env.GrupoFacilBugInbox
        T.ok(f.exporting)
        local text = a.ui.state(f.body.box).text
        local i1, i3 = text:find("problema número 1", 1, true), text:find("problema número 3", 1, true)
        T.ok(i1 and i3 and i1 < i3, "ordem do export")
        T.ok(a.ui.focus == f.body.box, "foco para Ctrl+C")
        T.clean(a)
    end)

    it("aviso de 'não está no disco' e o botão Gravar somem depois do reload", function()
        local w, a, p = withReports(1)
        a:slash("/gf bugs")
        local f = a.env.GrupoFacilBugInbox
        T.match(a:text(f.disk), "1 not on disk yet")
        T.ok(f.flush:IsEnabled())
        a:click(f.flush)
        T.ok(H.shown(a, a.env.GrupoFacilReloadPrompt))
        a:click(a.env.GrupoFacilReloadButton)
        w:advance(0.1)
        a:slash("/gf bugs")
        f = a.env.GrupoFacilBugInbox
        T.match(a:text(f.disk), "All saved on disk")
        T.no(f.flush:IsEnabled())
        T.clean(a)
    end)

    it("'Aceitar novos reports' desligado faz o jogador esperar", function()
        local w, a, p = setup()
        a:slash("/gf bugs")
        local f = a.env.GrupoFacilBugInbox
        T.ok(f.accept:GetChecked())
        a:click(f.accept)
        T.eq(H.db(a).acceptReports, false)
        local id = H.ns(p).SubmitBug("x", "bug", true)
        w:advance(120)
        T.eq(H.db(p).bugs[id].state, "queued")
        a:slash("/gf bugs accept on")
        T.eq(H.db(a).acceptReports, true)
        T.clean(a)
    end)

    it("chega um report com a caixa aberta: a lista atualiza sozinha", function()
        local w, a, p = setup()
        a:slash("/gf bugs")
        local f = a.env.GrupoFacilBugInbox
        T.ok(H.shown(a, f.emptyFS))
        H.ns(p).SubmitBug("novo", "bug", true)
        w:advance(30)
        T.eq(a:text(f.newBtn), "New (1)")
        T.no(H.shown(a, f.emptyFS))
        T.has(a:chatLines(), "new bug report from Jogador")
    end)

    it("comandos de texto: show, fix por prefixo do id, id ambíguo e desconhecido", function()
        local w, a, p = withReports(2)
        local ids = {}
        for id in pairs(H.db(a).inbox) do ids[#ids + 1] = id end
        a:clearChat()
        a:slash("/gf bugs show " .. ids[1]:sub(1, 12))
        T.has(a:chatLines(), "problema número")
        a:clearChat()
        a:slash("/gf bugs show zzz")
        T.has(a:chatLines(), "no report with id zzz")
        a:clearChat()
        a:slash("/gf bugs fix " .. ids[1]:sub(1, 3) .. " nota")
        T.has(a:chatLines(), "more than one report", "os dois ids começam igual")
        a:slash("/gf bugs dup " .. ids[2] .. " igual ao outro")
        T.eq(H.db(a).inbox[ids[2]].status, "dup")
        a:clearChat()
        a:slash("/gf bugs new")
        T.has(a:chatLines(), "bug reports: 2 %(new: 1%)")
        a:slash("/gf bugs flush")
        T.ok(H.shown(a, a.env.GrupoFacilReloadPrompt))
        a:slash("/gf bugs qualquer")
        T.has(a:chatLines(), "/gf bugs %[new")
        T.clean(a)
    end)

    it("opções do admin mostram o botão da caixa com a contagem", function()
        local w, a, p = withReports(2)
        a:slash("/gf options help")
        local found = H.find(a, a.env.GrupoFacilOptionsFrame, "^Bug reports")
        T.ok(found and H.shown(a, found), "botão da caixa nas opções")
        T.eq(a:text(found), "Bug reports (new: 2)")
        a:click(found)
        T.ok(H.shown(a, a.env.GrupoFacilBugInbox))
        -- o jogador comum não vê
        p:slash("/gf options help")
        T.eq(H.find(p, p.env.GrupoFacilOptionsFrame, "^Bug reports", true), nil, "jogador vê a caixa")
    end)

    it("lista do arquivo: Bagael Bagacera é o admin, recebe de outro jogador; outro Bagael não é admin", function()
        local w = H.world() -- sem sobrescrever: vale NS.BUG_ADMINS de BugReport.lua
        local a = H.login(w, { name = "Bagael", surname = "Bagacera", account = "AUTOR" })
        local p = H.login(w, { name = "Jogador", surname = "Silva", account = "JOGADOR" })
        local x = H.login(w, { name = "Bagael", surname = "Outro", account = "OUTRO", realm = "x" })
        w:advance(15)
        T.ok(H.ns(a).bugAdmin, "Bagael Bagacera deveria ser admin")
        T.no(H.ns(p).bugAdmin)
        T.no(H.ns(x).bugAdmin, "outro Bagael virou admin")
        local id = H.ns(p).SubmitBug("chegou?", "bug", true)
        w:advance(60)
        T.ok(H.db(a).inbox[id], "não chegou ao admin")
        T.eq(H.db(a).inbox[id].from, "Jogador Silva")
        T.match(H.db(a).inbox[id].body, "\nchar=Jogador Silva[\n%-]")
        T.clean(p); T.clean(a)
    end)
end)
