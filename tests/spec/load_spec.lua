-- Carga do addon, SavedVariables, migrações e regras de segurança com a janela da Blizzard.
local T = require("t")
local H = require("helpers")
local describe, it = T.describe, T.it

describe("carga e SavedVariables", function()
    it("primeiro login: padrões completos, sem erro, aviso de boas-vindas uma vez por conta", function()
        local w = H.world()
        local c = H.login(w)
        local db = H.db(c)
        T.eq(db.sendMode, "direto")
        T.eq(db.autoOpen, true)
        T.eq(db.docked, true)
        T.eq(db.filters.mode, "players")
        T.eq(db.filters.sort, "level")
        T.eq(db.filters.hideDelisted, true)
        T.eq(type(db.filters.classes), "table")
        T.eq(type(db.blocked), "table")
        T.eq(H.ns(c).VERSION, "dev", "TOC com @project-version@ vira dev")
        w:advance(8)
        T.has(c:chatLines(), "ready%. Open Looking For Group or type /gf")
        c:reload()
        w:advance(8)
        local n = 0
        for _, l in ipairs(c:chatLines()) do if l:find("ready%. Open") then n = n + 1 end end
        T.eq(n, 1, "boas-vindas só uma vez")
        local other = H.login(w, { name = "Alt", account = c.account })
        w:advance(8)
        T.hasnt(other:chatLines(), "ready%. Open", "uma vez por conta, não por personagem")
        T.clean(c)
    end)

    it("versão publicada vem do TOC", function()
        local w = H.world()
        w.addons.GrupoFacil.meta.Version = "0.13.0"
        local c = H.login(w)
        T.eq(H.ns(c).VERSION, "0.13.0")
    end)

    it("valores salvos são mantidos e o que falta é completado", function()
        local w = H.world()
        local c = H.login(w, { name = "Velho", account = "V" })
        local db = H.db(c)
        db.sendMode = "preencher"
        db.filters.mode = "groups"
        db.filters.classes = { MAGE = true }
        db.filters.activities = nil
        db.filters.sort = nil
        db.blocked = { fulano = "Fulano" }
        c:reload()
        db = H.db(c)
        T.eq(db.sendMode, "preencher")
        T.eq(db.filters.mode, "groups")
        T.eq(db.filters.classes.MAGE, true)
        T.eq(db.filters.sort, "level")
        T.eq(type(db.filters.activities), "table")
        T.eq(db.blocked.fulano, "Fulano")
        T.clean(c)
    end)

    it("migração da 0.1/0.2: o texto padrão em português volta ao padrão em inglês; texto próprio fica", function()
        local w = H.world()
        local c = H.login(w, { name = "Mig", account = "M" })
        H.db(c).template = "Olá, sou {classe} {spec} {level}, posso me juntar a vocês?"
        c:reload()
        T.eq(H.db(c).template, nil)
        H.db(c).template = "Meu texto {level}"
        c:reload()
        T.eq(H.db(c).template, "Meu texto {level}")
    end)

    it("migração nunca apaga a fila de bug report nem a caixa de entrada", function()
        local w = H.world()
        local c = H.login(w, { name = "Fila", account = "F" })
        H.db(c).bugs.abc = { id = "abc", ts = 1, state = "queued", body = "x", tries = 0 }
        H.db(c).inbox.def = { id = "def", from = "X", recvAt = 1, status = "new", body = "y" }
        c:reload()
        T.ok(H.db(c).bugs.abc)
        T.ok(H.db(c).inbox.def)
        T.eq(H.db(c).bugSchema, "bugq/1")
    end)

    it("janela do LFG carregada depois do login: abre o GrupoFacil junto e fecha junto", function()
        local w = H.world()
        local c = H.login(w)
        w:advance(1)
        T.no(H.shown(c, c.env.GrupoFacilFrame))
        c:openLFG()
        T.ok(H.shown(c, c.env.GrupoFacilFrame), "autoOpen")
        local p, rel, rp = c.env.GrupoFacilFrame:GetPoint(1)
        T.eq(rel, c.env.LFGParentFrame, "encaixado ao lado do LFG")
        T.eq(p .. rp, "TOPLEFTTOPRIGHT")
        c:closeLFG()
        T.no(H.shown(c, c.env.GrupoFacilFrame), "fecha junto quando abriu junto")
        c:slash("/gf")
        T.ok(H.shown(c, c.env.GrupoFacilFrame))
        c:openLFG(); c:closeLFG()
        T.clean(c)
    end)

    it("janela do LFG já carregada no login também é ligada (PLAYER_LOGIN)", function()
        local w = H.world()
        local c = H.login(w, { lfgLoadedAtLogin = true })
        c.env.LFGParentFrame:Show()
        T.ok(H.shown(c, c.env.GrupoFacilFrame))
    end)

    it("autoOpen desligado: o LFG abre sozinho", function()
        local w = H.world()
        local c = H.login(w)
        c:slash("/gf auto off")
        c:openLFG()
        T.no(H.shown(c, c.env.GrupoFacilFrame))
        T.has(c:chatLines(), "open together with Looking For Group: off")
    end)

    it("segurança: nada é escrito na janela da Blizzard e C_LFGList.Search só tem hook seguro", function()
        local w = H.world()
        H.sampleListings(w)
        local c = H.login(w)
        c:openLFG()
        H.search(w, c)
        c:slash("/gf")
        c:slash("/gf")
        local ns = H.ns(c)
        w:advance(5)
        ns.SearchAgain()
        w:advance(15)
        T.eq(#w.blizzardWrites, 0, "escreveu em frame da Blizzard: " .. tostring(w.blizzardWrites[1] and w.blizzardWrites[1].key))
        local search = c.env.C_LFGList.Search
        T.ok(w.secureHooks[search], "C_LFGList.Search foi trocado por algo que não é hooksecurefunc")
        T.clean(c)
    end)

    it("/gf hook off: depois do reload não há hook; Buscar de novo usa os dropdowns", function()
        local w = H.world()
        H.sampleListings(w)
        local c = H.login(w)
        c:slash("/gf hook off")
        T.has(c:chatLines(), "applies after /reload")
        c:reload()
        T.eq(w.secureHooks[c.env.C_LFGList.Search], nil)
        c:nativeSearch(2, { 1, 2 })
        w:advance(5)
        local ns = H.ns(c)
        local ok = ns.SearchAgain()
        T.ok(ok)
        T.eq(c.lastSearch.activities[2], 2, "atividades lidas do dropdown")
        T.clean(c)
    end)

    it("retrato do ambiente 5 s depois do login, com a lista de APIs", function()
        local w = H.world()
        local c = H.login(w)
        w:advance(6)
        local snap = H.db(c).diag.snapshot.login
        T.ok(snap, "snapshot")
        T.eq(snap.apis["C_LFGList.Search"], "function")
        T.match(snap.client, "toc=16001")
        T.clean(c)
    end)

    it("sem as APIs opcionais (C_AddOns, eventos novos) o addon carrega sem erro", function()
        local w = H.world({ missingEvents = { "LFG_LIST_ROLE_UPDATE", "LUA_WARNING", "BN_FRIEND_INFO_CHANGED" } })
        local c = H.login(w)
        w:advance(10)
        T.clean(c)
        local found
        for _, t in ipairs(H.db(c).diag.trace) do if t.m:find("LFG_LIST_ROLE_UPDATE indispon") then found = true end end
        T.ok(found, "registra no rastro que o evento não existe")
    end)
end)
