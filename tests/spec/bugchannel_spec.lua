-- Canal de bug report (BugChannel.lua + BugReport.lua), protocolo 1, de ponta a ponta:
-- dois ou mais clientes ligados pela rede simulada, com relógio, disco, crash e reload.
local T = require("t")
local H = require("helpers")
local describe, it = T.describe, T.it

local ADMINS = { "Bael", "Bagael" }
local function bugWorld(config)
    config = config or {}
    local admins = config.admins or ADMINS
    config.beforeAddonLoaded = function(_, ns) ns.BUG_ADMINS = admins end
    return H.world(config)
end
local function admin(w, opts)
    opts = opts or {}
    opts.name = opts.name or "Bael"
    opts.account = opts.account or "AUTOR"
    return H.login(w, opts)
end
local function player(w, opts)
    opts = opts or {}
    opts.name = opts.name or "Jogador"
    opts.account = opts.account or "JOGADOR"
    return H.login(w, opts)
end
local function bugs(c) return H.db(c).bugs end
local function inbox(c) return H.db(c).inbox end
local function only(t) local k, v = next(t); return v, k end
local function count(t) local n = 0; for _ in pairs(t) do n = n + 1 end; return n end
local function report(c, text)
    local id, why = H.ns(c).SubmitBug(text or "o botão Pedir vaga não faz nada", "bug", true)
    T.ok(id, "report não criado: " .. tostring(why))
    return id
end
-- nada de "No player named..." na tela do jogador e nenhuma mensagem acima do limite
local function quiet(w, c)
    T.hasnt(c:chatLines("system"), "No player named", "linha de sistema vazou")
    T.eq(w.net.tooLong, nil, "mensagem acima de 255 bytes")
    T.clean(c)
end

describe("canal de bug report", function()
    it("escape, corte e checksum: só ASCII imprimível no canal e %XX nunca partido", function()
        local w = bugWorld()
        local c = player(w)
        local BC = H.ns(c).BugChannel
        local s = "ação ~ | 100% \n fim\0" .. string.rep("ç", 200)
        local e = BC._esc(s)
        T.nomatch(e, "[~|\n%z\128-\255]", "caractere proibido no texto escapado")
        T.eq(BC._unesc(e), s)
        for _, n in ipairs({ 3, 7, 170 }) do
            local parts = BC._split(e, n)
            T.eq(table.concat(parts), e)
            for _, p in ipairs(parts) do
                T.ok(#p <= n, "pedaço maior que o limite")
                T.nomatch(p, "%%%x?$", "pedaço termina no meio de um %XX")
            end
        end
        T.eq(BC._adler("Wikipedia"), 300286872)
        T.clean(c)
    end)

    it("caminho feliz: A1, continua guardado até o reload do admin, depois A2 e o corpo é apagado", function()
        local w = bugWorld()
        local a = admin(w)
        local p = player(w)
        w:advance(15)
        local id = report(p, "Pedir vaga não envia nada")
        w:advance(30)
        local e = bugs(p)[id]
        T.eq(e.state, "received")
        T.ok(e.body, "o jogador não pode apagar antes do A2")
        local got = inbox(a)[id]
        T.ok(got, "admin não recebeu")
        T.eq(got.from, "Jogador")
        T.eq(got.status, "new")
        T.match(got.body, "note=Pedir vaga não envia nada")
        T.match(got.body, "^addon=GrupoFacil\nver=")
        T.has(a:chatLines(), "new bug report from Jogador")
        w:advance(300)
        T.eq(bugs(p)[id].state, "received", "sem reload do admin nada é apagado")
        a:reload()
        w:advance(70)
        e = bugs(p)[id]
        T.eq(e.state, "done")
        T.eq(e.body, nil)
        T.ok(e.doneAt)
        T.has(p:chatLines(), "received and saved by the author")
        quiet(w, p)
        T.clean(a)
    end)

    it("o corpo chega idêntico (acentos, | e várias linhas) mesmo grande", function()
        local w = bugWorld()
        local a = admin(w)
        local p = player(w)
        w:advance(15)
        local text = ("Linha com ação|pipe e ~til;\n"):rep(60)
        local id = report(p, text)
        w:advance(120)
        local got = inbox(a)[id]
        T.ok(got, "não chegou")
        T.eq(got.body, H.db(p).bugs[id].body)
        quiet(w, p)
    end)

    it("crash do admin depois do A1: U, o jogador reenvia e nada se perde", function()
        local w = bugWorld()
        local a = admin(w)
        local p = player(w)
        w:advance(15)
        local id = report(p)
        w:advance(30)
        T.eq(bugs(p)[id].state, "received")
        a:crash() -- nada gravado: o admin esquece o report
        w:advance(20)
        a = admin(w)
        T.eq(inbox(a)[id], nil, "crash não grava")
        w:advance(400)
        T.ok(inbox(a)[id], "jogador deveria ter reenviado depois do U")
        T.eq(bugs(p)[id].state, "received")
        a:reload()
        w:advance(120)
        T.eq(bugs(p)[id].state, "done")
        quiet(w, p)
        T.clean(a)
    end)

    it("pacote D perdido: N com a lista e reenvio só do que faltou", function()
        local w = bugWorld()
        local a = admin(w)
        local p = player(w)
        w:advance(15)
        local dropped = false
        w.net.dropFn = function(r)
            if not dropped and r.msg:find("^1~D~[^~]+~2~") then dropped = true; return true end
        end
        local id = report(p, ("x"):rep(900))
        w:advance(60)
        T.ok(dropped, "o teste não derrubou o pacote")
        T.ok(inbox(a)[id], "não completou depois do N")
        local resent = w.net:find(function(r) return r.from == "Jogador" and r.msg:find("^1~D~[^~]+~2~") end)
        T.eq(#resent, 2, "o chunk 2 deveria ir duas vezes")
        local first = w.net:find(function(r) return r.from == "Jogador" and r.msg:find("^1~D~[^~]+~1~") end)
        T.eq(#first, 1, "o chunk 1 não deveria ser reenviado")
        quiet(w, p)
    end)

    it("pacote corrompido: checksum falha, N all, reenvio completo", function()
        local w = bugWorld()
        local a = admin(w)
        local p = player(w)
        w:advance(15)
        local mangled = false
        w.net.mangleFn = function(r)
            if not mangled and r.msg:find("^1~D~") then mangled = true; return r.msg:sub(1, -2) .. "Z" end
        end
        local id = report(p, ("abc"):rep(100))
        w:advance(200)
        T.ok(mangled)
        T.ok(inbox(a)[id], "não recuperou do checksum")
        T.eq(inbox(a)[id].body, bugs(p)[id].body)
        quiet(w, p)
    end)

    it("reenvio do mesmo id não duplica na caixa de entrada", function()
        local w = bugWorld()
        local a = admin(w)
        local p = player(w)
        w:advance(15)
        local id = report(p)
        w:advance(30)
        -- o jogador relogou no meio (estado volta a queued) e reenvia tudo
        bugs(p)[id].state = "queued"
        p:reload()
        w:advance(60)
        T.eq(count(inbox(a)), 1)
        T.eq(bugs(p)[id].state, "received")
        quiet(w, p)
    end)

    it("um falso admin respondendo PONG é ignorado", function()
        local w = bugWorld()
        local p = player(w)
        local x = H.login(w, { name = "Impostor", account = "X" })
        w:advance(15)
        local id = report(p)
        for _ = 1, 5 do
            x.env.C_ChatInfo.SendAddonMessage("GFBUG", "1~P~1", "WHISPER", "Jogador")
            w:advance(10)
        end
        local sentToImpostor = w.net:find(function(r) return r.from == "Jogador" and r.to == "Impostor" end)
        T.eq(#sentToImpostor, 0)
        T.eq(bugs(p)[id].state, "queued")
        quiet(w, p)
    end)

    it("admin offline 10 min, jogador sai e volta: entrega quando o admin aparece, sem linha de sistema", function()
        local w = bugWorld()
        local p = player(w)
        w:advance(15)
        local id = report(p)
        w:advance(600)
        T.eq(bugs(p)[id].state, "queued")
        local pings = w.net:find(function(r) return r.from == "Jogador" and r.msg == "1~PING" end)
        T.ok(#pings <= 2 * 6, "backoff: pings demais em 10 min (" .. #pings .. ")")
        T.eq(p.hiddenSystem ~= nil, true, "o filtro deveria ter escondido as linhas de sistema")
        p:logout()
        w:advance(30)
        p = player(w)
        local a = admin(w)
        w:advance(90)
        T.eq(bugs(p)[id].state, "received")
        T.ok(inbox(a)[id])
        quiet(w, p)
    end)

    it("o jogador crasha logo depois de criar o report: perde (limite conhecido); com /reload antes, não", function()
        local w = bugWorld()
        local p = player(w)
        w:advance(15)
        local lost = report(p, "vai se perder")
        p:crash()
        w:advance(5)
        p = player(w)
        T.eq(bugs(p)[lost], nil)
        local kept = report(p, "fica guardado")
        p:reload()
        w:advance(1)
        p:crash()
        w:advance(5)
        p = player(w)
        T.ok(bugs(p)[kept], "o reload deveria ter gravado o report")
        T.eq(bugs(p)[kept].state, "queued")
    end)

    it("desfecho: Resolve manda F e o jogador vê o status e a nota", function()
        local w = bugWorld()
        local a = admin(w)
        local p = player(w)
        w:advance(15)
        local id = report(p)
        w:advance(30)
        T.ok(H.ns(a).ResolveBug(id, "fixed", "corrigido na 0.13"))
        w:advance(5)
        local e = bugs(p)[id]
        T.ok(e.resolved, "F não chegou")
        T.eq(e.resolved.status, "fixed")
        T.eq(e.resolved.note, "corrigido na 0.13")
        T.has(p:chatLines(), "your report " .. id:gsub("%-", "%%-") .. ": fixed %- corrigido na 0.13")
        quiet(w, p)
    end)

    it("desfecho por BugResolutions.lua no próximo login do admin chega ao jogador", function()
        local w = bugWorld()
        local a = admin(w)
        local p = player(w)
        w:advance(15)
        local id = report(p)
        w:advance(30)
        a:reload()
        w:advance(70)
        T.eq(bugs(p)[id].state, "done")
        p:logout()
        a:logout()
        -- a sessão Claude escreve o desfecho no arquivo do addon e o admin entra de novo
        a = admin(w, { beforeAddonLoaded = function(c, ns) ns.BUG_ADMINS = ADMINS; c.env.GF_BugResolutions = { [id] = { status = "wontfix", note = "comportamento do jogo" } } end })
        w:advance(20)
        T.eq(inbox(a)[id].status, "wontfix")
        a:reload() -- o status novo vai a disco
        p = player(w)
        w:advance(120)
        local e = bugs(p)[id]
        T.ok(e.resolved, "a consulta S do recibo deveria trazer o F")
        T.eq(e.resolved.status, "wontfix")
        quiet(w, p)
    end)

    it("dois admins da mesma conta: o inbox é o mesmo arquivo; trocar de personagem não perde nada", function()
        local w = bugWorld()
        local a = admin(w)
        local p = player(w)
        w:advance(15)
        local id = report(p)
        w:advance(30)
        a:logout()
        local b = admin(w, { name = "Bagael" })
        T.ok(inbox(b)[id], "SavedVariables da conta deveria ter o report")
        -- o jogador ainda fala com o Bael até o PONG dele vencer (300 s), depois acha o Bagael
        w:advance(420)
        T.eq(bugs(p)[id].state, "done", "o inbox carregado do disco é durável: A2")
        quiet(w, p)
        T.clean(b)
    end)

    it("admin reportando vai direto para a própria caixa de entrada, sem rede", function()
        local w = bugWorld()
        local a = admin(w)
        w:advance(15)
        local before = #w.net.log
        local id = report(a, "achei um bug")
        T.ok(inbox(a)[id])
        T.eq(bugs(a)[id].state, "done")
        w:advance(60)
        local mine = w.net:find(function(r) return r.from == "Bael" and r.msg ~= nil and r.prefix == "GFBUG" end)
        T.eq(#mine, 0)
        T.has(a:chatLines(), "saved in your own inbox")
        T.clean(a)
    end)

    it("limite por hora: o 21º report do mesmo jogador espera e chega depois", function()
        local w = bugWorld()
        local a = admin(w)
        local p = player(w)
        w:advance(15)
        local ids = {}
        for i = 1, 21 do ids[i] = report(p, "report " .. i); w:advance(1) end
        w:advance(21 * 40)
        T.eq(count(inbox(a)), 20)
        T.eq(bugs(p)[ids[21]] and bugs(p)[ids[21]].state, "queued")
        w:advance(3600)
        T.eq(count(inbox(a)), 21, "depois da hora deveria entrar")
        quiet(w, p)
    end)

    it("caixa cheia (500): R FULL e o report continua na fila do jogador", function()
        local w = bugWorld()
        local a = admin(w)
        local box = inbox(a)
        for i = 1, 500 do box["x" .. i] = { id = "x" .. i, from = "Alguem", recvAt = 1, status = "new", body = "b" } end
        local p = player(w)
        w:advance(15)
        local id = report(p)
        w:advance(60)
        T.eq(box[id], nil)
        T.eq(bugs(p)[id].state, "queued")
        quiet(w, p)
    end)

    it("admin desliga 'aceitar reports': o jogador mantém na fila", function()
        local w = bugWorld()
        local a = admin(w)
        H.db(a).acceptReports = false
        local p = player(w)
        w:advance(15)
        local id = report(p)
        w:advance(300)
        T.eq(bugs(p)[id].state, "queued")
        H.db(a).acceptReports = true
        w:advance(1000)
        T.ok(inbox(a)[id], "ao religar deveria chegar")
        quiet(w, p)
    end)

    it("versão de protocolo diferente: X, e o jogador avisa uma vez para atualizar", function()
        local w = bugWorld()
        local a = admin(w)
        local p = player(w)
        w:advance(15)
        p.env.C_ChatInfo.SendAddonMessage("GFBUG", "2~PING", "WHISPER", "Bael")
        w:advance(1)
        local x = w.net:find(function(r) return r.from == "Bael" and r.msg:find("^1~X~") end)
        T.eq(#x, 1)
        a.env.C_ChatInfo.SendAddonMessage("GFBUG", "2~X~2", "WHISPER", "Jogador")
        a.env.C_ChatInfo.SendAddonMessage("GFBUG", "2~X~2", "WHISPER", "Jogador")
        w:advance(1)
        local warn = 0
        for _, l in ipairs(p:chatLines()) do if l:find("newer bug report version") then warn = warn + 1 end end
        T.eq(warn, 1)
        quiet(w, p)
    end)

    it("recibo 'done' some depois de 30 dias", function()
        local w = bugWorld()
        local p = player(w)
        w:advance(5)
        bugs(p).velho = { id = "velho", ts = 1, state = "done", doneAt = w:epochNow() - 31 * 86400 }
        bugs(p).novo = { id = "novo", ts = 2, state = "done", doneAt = w:epochNow() - 5 * 86400 }
        p:reload()
        T.eq(bugs(p).velho, nil)
        T.ok(bugs(p).novo)
    end)

    it("mensagem de sistema de outro jogador offline continua aparecendo", function()
        local w = bugWorld()
        local p = player(w)
        w:advance(15)
        report(p)
        w:advance(60)
        p.env.SendChatMessage("oi", "WHISPER", nil, "Fulano")
        w:advance(1)
        T.has(p:chatLines("system"), "No player named 'Fulano'")
    end)

    it("reload do admin no meio da transferência (mensagens perdidas) se recupera", function()
        local w = bugWorld({ reloadTime = 3 })
        local a = admin(w)
        local p = player(w)
        w:advance(15)
        local id = report(p, ("y"):rep(3000))
        w:advance(6)
        a:reload()
        w:advance(600)
        T.ok(inbox(a)[id], "não recuperou")
        quiet(w, p)
    end)

    it("dois reports: um já 'received' e outro que expira sem A1 (admin some) não quebra o envio", function()
        -- o momento em que o envio expira cai, em algum ponto, junto da consulta S de 60 s:
        -- varre os atrasos para pegar esse encontro
        for delay = 0, 60, 2.5 do
            local w = bugWorld()
            local a = admin(w)
            local p = player(w)
            w:advance(15)
            local first = report(p, "primeiro")
            w:advance(30)
            T.eq(bugs(p)[first].state, "received")
            w:advance(delay)
            -- o admin cai sem gravar enquanto o segundo report está em voo
            local second = report(p, ("segundo "):rep(200))
            w:advance(0.5)
            a:crash()
            w:advance(200)
            T.clean(p, "atraso " .. delay .. ": erro de Lua no jogador quando um envio expira com outro report em received")
            a = admin(w)
            w:advance(1500)
            T.ok(inbox(a)[second], "atraso " .. delay .. ": o segundo deveria chegar quando o admin voltar")
            quiet(w, p)
        end
    end)

    it("nota de desfecho longa e acentuada cabe no limite de 255 bytes e chega ao jogador", function()
        local w = bugWorld()
        local a = admin(w)
        local p = player(w)
        w:advance(15)
        local id = report(p)
        w:advance(30)
        local note = ("ação não é só correção; "):rep(6)
        H.ns(a).ResolveBug(id, "fixed", note)
        w:advance(30)
        T.eq(w.net.tooLong, nil, "a mensagem F passou de 255 bytes")
        local e = bugs(p)[id]
        T.ok(e.resolved, "o F não chegou")
        T.ok(#e.resolved.note > 20)
        T.nomatch(e.resolved.note, "[\192-\255]$", "nota cortada no meio de um caractere UTF-8")
        T.clean(a)
    end)

    it("throttle por prefixo (dentro de instância): report grande chega sem perder pacote", function()
        local w = bugWorld()
        local a = admin(w)
        local p = player(w)
        p.data.inInstance = true
        w:advance(15)
        local id = report(p, ("dentro da masmorra "):rep(300))
        w:advance(600)
        T.ok((w.net.throttled or 0) > 0, "o cenário deveria acionar o throttle")
        T.ok(inbox(a)[id], "não chegou com throttle")
        T.eq(inbox(a)[id].body, bugs(p)[id].body)
        quiet(w, p)
    end)

    for _, mode in ipairs({ "bool", "nil", "wrapped" }) do
        it("retorno de SendAddonMessage no formato '" .. mode .. "' também funciona", function()
            local w = bugWorld({ addonReturn = mode })
            local a = admin(w)
            local p = player(w)
            w:advance(15)
            local id = report(p)
            w:advance(60)
            T.ok(inbox(a)[id])
            quiet(w, p)
        end)
    end

    it("sem C_ChatInfo.SendAddonMessage usa o SendAddonMessage global", function()
        local w = bugWorld({ noCChatInfoSend = true })
        local a = admin(w)
        local p = player(w)
        w:advance(15)
        local id = report(p)
        w:advance(60)
        T.ok(inbox(a)[id])
    end)

    it("cliente 12.x que devolve TargetOffline: um admin offline não atrasa a entrega ao outro", function()
        local w = bugWorld({ offline = "enum" })
        local b = admin(w, { name = "Bagael" }) -- Bael (1º da lista) está offline
        local p = player(w)
        w:advance(15)
        local id = report(p)
        w:advance(60)
        T.ok(inbox(b)[id], "não chegou ao admin online em 60 s")
        quiet(w, p)
    end)

    it("personagem com o nome do admin mas sem a lista de admins não responde PONG", function()
        local w = bugWorld()
        local p = player(w)
        local other = H.login(w, { name = "Bael", account = "AUTOR", beforeAddonLoaded = function(_, ns) ns.BUG_ADMINS = { "Ninguem" } end })
        -- esse "Bael" tem o addon, mas não se considera admin; o prefixo está registrado mesmo assim
        T.ok(other.prefixes.GFBUG, "todo cliente registra o prefixo")
        w:advance(15)
        local id = report(p)
        w:advance(60)
        T.eq(bugs(p)[id].state, "queued", "um cliente que não é admin não responde PONG")
        quiet(w, p)
    end)
end)
